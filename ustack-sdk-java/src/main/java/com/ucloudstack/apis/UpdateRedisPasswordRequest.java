package com.ucloudstack.apis;

import com.ucloudstack.common.annotation.NotEmpty;
import com.ucloudstack.common.annotation.OpenAPIParam;
import com.ucloudstack.common.request.Request;
import java.util.List;
import java.util.Map;
import com.ucloudstack.models.*;

public class UpdateRedisPasswordRequest extends Request {

    /** 租户ID，资源所属租户 */
    
    @OpenAPIParam("CompanyID")
    private Integer companyIDParam;

    /** 新密码，满足paaspassword校验规则 */
    
    @OpenAPIParam("Password")
    private String passwordParam;

    /** Redis实例ID，指定要更新密码的实例；注意：资源必须为AVAILABLE且状态为Running */
    @NotEmpty
    @OpenAPIParam("RedisID")
    private String redisIDParam;

    /** 地域ID，资源所属的物理区域 */
    @NotEmpty
    @OpenAPIParam("Region")
    private String regionParam;


    public Integer getCompanyID() {
        return companyIDParam;
    }

    public void setCompanyID(Integer companyIDParam) {
        this.companyIDParam = companyIDParam;
    }

    public String getPassword() {
        return passwordParam;
    }

    public void setPassword(String passwordParam) {
        this.passwordParam = passwordParam;
    }

    public String getRedisID() {
        return redisIDParam;
    }

    public void setRedisID(String redisIDParam) {
        this.redisIDParam = redisIDParam;
    }

    public String getRegion() {
        return regionParam;
    }

    public void setRegion(String regionParam) {
        this.regionParam = regionParam;
    }

}
